def _filename(raw: str) -> str | None:
    name = re.sub(r"[^\w.\- ]", "_", raw.strip())[:80].strip(". ")
    ext = name.rsplit(".", 1)[-1].lower() if "." in name else ""
    return name if ext in FILE_TYPES else None


def make_showcase(frame_b64: str | None, frame_type: str) -> Callable[[dict], dict]:
    """A showcase handler for this turn, holding the camera frame (if any)
    for an image drawn from the board."""

    def showcase(args: dict) -> dict:
        kind = args.get("kind")
        if kind not in KINDS:
            return {"ok": False, "error": f"kind must be one of {KINDS}"}
        title = str(args.get("title") or "").strip()[:80] or kind.title()
        caption = str(args.get("caption") or "").strip()[:300]
        content = str(args.get("content") or "")
        if len(content) > MAX_CONTENT_CHARS:
            return {"ok": False, "error": f"content is over {MAX_CONTENT_CHARS} characters"}
        item: dict = {"kind": kind, "title": title, "caption": caption}

        if kind in ("equation", "text", "code"):
            if not content.strip():
                return {"ok": False, "error": f"{kind} needs content"}
            item["content"] = content.strip()
            if kind == "code":
                item["language"] = str(args.get("language") or "").strip()[:20]
        elif kind == "file":
            name = _filename(str(args.get("filename") or ""))
            if not name:
                return {"ok": False, "error": f"filename needs one of these extensions: {sorted(FILE_TYPES)}"}
            if not content:
                return {"ok": False, "error": "file needs content"}
            item.update(content=content, filename=name, mime=FILE_TYPES[name.rsplit('.', 1)[1].lower()])
        else:
            prompt = str(args.get("image_prompt") or args.get("content") or "").strip()[:1500]
            if not prompt:
                return {"ok": False, "error": "image needs image_prompt"}
            reference = frame_b64 if args.get("from_camera") else None
            if args.get("from_camera") and not reference:
                return {"ok": False, "error": "The camera is off, so there is no frame to work from."}
            try:
                image = generate_image(prompt, reference, frame_type)
            except GeminiNotConfigured as exc:
                return {"ok": False, "error": str(exc)}
            except AllModelsExhausted as exc:
                return {"ok": False, "error": f"No image model would take it - {exc.detail()}"}
            except Exception as exc:  # noqa: BLE001 — say why, rather than failing the turn
                return {"ok": False, "error": f"Image generation failed: {exc}"}
            # image_data goes to the console only; the orchestrator strips it
            # from what the model and the logs see.
            item.update(image_data=image["image"], mime=image["mime"])
            if not caption and image["note"]:
                item["caption"] = image["note"][:300]

        note = "On his screen now, in its own window."
        if kind == "text":
            # A .txt in Drive as well as on screen. Saving is a bonus: if Drive
            # fails, the window still opens and the reply can say so.
            try:
                saved = save_note(title, item["content"])
                item.update(filename=saved["name"], mime="text/plain", drive_link=saved["link"])
                note += f" Saved to Drive as \"{saved['name']}\" in Jarvis Notes."
            except Exception as exc:  # noqa: BLE001
                item.update(filename=f"{title}.txt", mime="text/plain")
                note += f" Not saved to Drive: {exc}"
        return {"ok": True, "showcase": item, "note": note}

    return showcase


def state_line(state: dict | None) -> str | None:
    """What the showcase window is showing, for CONSOLE_STATE."""
    showing = (state or {}).get("showcase")
    if not isinstance(showing, dict):
        return None
    return f"Showcase window open: \"{str(showing.get('title'))[:80]}\" ({showing.get('kind')})."
