# Jarvis putting something on screen: an equation, worked steps, code, a
# file to download or an image, in its own window in the console
# (web/src/components/showcase/). It is for what should be LOOKED AT -
# chat text is plain and the voice cannot read out an integral - so the
# reply can point at the window instead of reciting it.
#
# Console channel only, like the console tool. Notes (kind text) are also
# saved to Drive as .txt files (app/tools/notes.py), to find again later.

KINDS = ["equation", "text", "code", "file", "image"]
MAX_CONTENT_CHARS = 60_000
# Text files only: everything here is written by the model as text.
FILE_TYPES = {
    "txt": "text/plain", "md": "text/markdown", "csv": "text/csv", "json": "application/json",
    "tex": "application/x-tex", "py": "text/x-python", "js": "text/javascript",
    "ts": "text/typescript", "html": "text/html", "css": "text/css", "scad": "text/plain",
    "yaml": "text/yaml", "yml": "text/yaml", "xml": "application/xml", "sql": "text/plain",
    "ics": "text/calendar", "svg": "image/svg+xml",
}

